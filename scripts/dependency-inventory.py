#!/usr/bin/env python3
"""Validate complete SBOM scan coverage and optionally refresh committed license metadata."""
from datetime import datetime, timezone
from pathlib import Path
import argparse
import hashlib
import json
import sys

from maven_evidence import reactor_modules

ROOT = Path(__file__).resolve().parents[1]
ORIGINAL_GROUP = 'io.github.cheshmakzanoon.portfolio'


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def pom_manifest(root):
    return {str(module.directory.relative_to(root) / 'pom.xml'): sha256(module.directory / 'pom.xml')
            for module in reactor_modules(root)}


def require_inputs(root, before):
    if before != pom_manifest(root):
        raise ValueError('POM inputs changed while generating/scanning the inventory')


def load(path):
    with path.open(encoding='utf-8') as source:
        return json.load(source)



def license_values(component):
    entries = component.get('licenses')
    if not isinstance(entries, list) or not entries:
        raise ValueError('Missing published licenses or SHA-256: ' + component['purl'])
    values = []
    for entry in entries:
        if not isinstance(entry, dict):
            raise ValueError('Invalid published license entry: ' + component['purl'])
        if 'expression' in entry:
            value = entry['expression']
        else:
            details = entry.get('license', {})
            if not isinstance(details, dict):
                raise ValueError('Invalid published license entry: ' + component['purl'])
            value = details.get('id') or details.get('name')
        if not isinstance(value, str) or not value.strip():
            raise ValueError('Empty published license entry: ' + component['purl'])
        values.append(value.strip())
    return values


def inspect(bom, scan):
    if bom.get('bomFormat') != 'CycloneDX' or bom.get('specVersion') != '1.6':
        raise ValueError('Expected the pinned CycloneDX 1.6 inventory')
    components = bom.get('components', [])
    root = bom.get('metadata', {}).get('component', {})
    if not components or not root.get('purl'):
        raise ValueError('Missing resolved reactor inventory')
    artifacts = [root, *components]
    identifiers = [component.get('purl') for component in artifacts]
    references = [component.get('bom-ref') for component in artifacts]
    if (any(not value for value in identifiers + references)
            or len(set(identifiers)) != len(identifiers)
            or len(set(references)) != len(references)):
        raise ValueError('Missing or duplicate component identities')
    graph = bom.get('dependencies', [])
    if {node.get('ref') for node in graph} != set(references):
        raise ValueError('Incomplete dependency graph')
    if any(set(node.get('dependsOn', [])) - set(references) for node in graph):
        raise ValueError('Unresolved dependency graph reference')
    external = [component for component in components if component.get('group') != ORIGINAL_GROUP]
    if not external:
        raise ValueError('Inventory contains no external library dependencies')
    for component in external:
        license_values(component)
        if not any(
                digest.get('alg') == 'SHA-256' and len(digest.get('content', '')) == 64
                and all(c in '0123456789abcdef' for c in digest['content'])
                for digest in component.get('hashes', [])):
            raise ValueError('Missing published licenses or SHA-256: ' + component['purl'])
    if scan.get('ArtifactType') != 'cyclonedx':
        raise ValueError('Expected a Trivy CycloneDX scan')
    observed = set()
    findings = []
    for result in scan.get('Results', []):
        if result.get('Class') != 'lang-pkgs' or result.get('Type') != 'jar':
            raise ValueError('Unexpected dependency scan result scope')
        observed.update(package.get('Identifier', {}).get('PURL') for package in result.get('Packages', []))
        findings.extend(result.get('Vulnerabilities', []))
    if observed != set(identifiers):
        raise ValueError('Scanner package coverage differs from the resolved inventory')
    if any(finding.get('Severity') in ('HIGH', 'CRITICAL') for finding in findings):
        raise ValueError('Unresolved HIGH/CRITICAL library findings')
    return components, external


def license_table(external):
    lines = [
        '# Dependency license inventory', '',
        'Generated by `scripts/dependency-inventory.py` from the executed CycloneDX 2.9.3 aggregate goal. '
        'The [CycloneDX 1.6 inventory](portfolio.cdx.json) retains exact versions, dependency edges, '
        'published license metadata and artifact hashes. Compile, runtime, provided and system scopes '
        'are included; tests, build plugins and container contents are excluded. '
        '[Input and execution metadata](evidence.json) identifies the current POMs.', '',
        'Published license entries preserve upstream metadata, including alternative licenses; they do not '
        'choose a legal interpretation. Original repository code uses the root Apache-2.0 [license](../../LICENSE). '
        'License metadata and [vulnerability observations](security.json) have separate purposes.', '',
        '| Component | Version | Published license identifiers or names |',
        '| --- | --- | --- |']
    for component in sorted(external, key=lambda c: (c.get('group', ''), c['name'], c['version'])):
        licenses = license_values(component)
        cells = [component.get('group', '') + ':' + component['name'], component['version'], '; '.join(licenses)]
        lines.append('| ' + ' | '.join(cell.replace('|', '\\|').replace('\n', ' ') for cell in cells) + ' |')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--snapshot', type=Path, help='write current POM hashes before inventory generation')
    parser.add_argument('--pom-inputs', type=Path, help='require POM hashes captured before Maven')
    parser.add_argument('--publish', action='store_true', help='refresh committed inventory/licenses after successful validation')
    parser.add_argument('bom', nargs='?', type=Path)
    parser.add_argument('scan', nargs='?', type=Path)
    args = parser.parse_args()
    if args.snapshot:
        if args.bom or args.scan or args.publish or args.pom_inputs:
            parser.error('--snapshot is a separate operation')
        args.snapshot.write_text(json.dumps(pom_manifest(ROOT), indent=2) + '\n')
        return 0
    if not args.bom or not args.scan or not args.pom_inputs:
        parser.error('bom, scan and --pom-inputs are required')
    before = load(args.pom_inputs)
    require_inputs(ROOT, before)
    components, external = inspect(load(args.bom), load(args.scan))
    summary = {'observedAtUtc': datetime.now(timezone.utc).isoformat(),
               'generator': 'CycloneDX Maven plugin 2.9.3', 'format': 'CycloneDX 1.6',
               'command': './scripts/security-scan.sh', 'bomSha256': sha256(args.bom),
               'scanSha256': sha256(args.scan), 'pomManifest': before,
               'originalComponents': len(components) - len(external), 'externalComponents': len(external),
               'externalComponentsWithPublishedLicenseMetadata': len(external),
               'scannedPackages': len(components) + 1, 'highCriticalFindings': 0,
               'scope': 'Compile/runtime/provided/system libraries; excludes tests, build plugins and containers',
               'limitations': ['Published license metadata is not a legal assessment.',
                               'The library scan does not certify container or source security.',
                               'Regenerate whenever POM inputs change; preserve historical measurement evidence separately.']}
    if args.publish:
        table = license_table(external)
        destination = ROOT / 'docs/dependencies'
        destination.mkdir(parents=True, exist_ok=True)
        (destination / 'portfolio.cdx.json').write_bytes(args.bom.read_bytes())
        (destination / 'LICENSES.md').write_text(table, encoding='utf-8')
        (destination / 'evidence.json').write_text(json.dumps(summary, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({key: value for key, value in summary.items() if key != 'pomManifest'}, indent=2))
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (ValueError, OSError, KeyError, TypeError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
